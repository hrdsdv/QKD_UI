# Конфигурация сетевых адресов для QKD системы (REST API)
# 
# Для работы на двух разных ПК:
# 1. На ПК с сервером А установите SERVER_A_HOST = '0.0.0.0' (слушать все интерфейсы)
# 2. На ПК с сервером Б установите SERVER_B_HOST = '0.0.0.0'
# 3. Укажите реальные IP-адреса в REMOTE_SERVER_A и REMOTE_SERVER_B
#
# Пример:
# ПК 1 (Абонент А): IP = 192.168.1.100
# ПК 2 (Абонент Б): IP = 192.168.1.101
#
# На ПК 1 (server_user_1):
#   SERVER_A_HOST = '0.0.0.0'
#   REMOTE_SERVER_B = 'http://192.168.1.101:5001'
#
# На ПК 2 (server_user_2):
#   SERVER_B_HOST = '0.0.0.0'
#   REMOTE_SERVER_A = 'http://192.168.1.100:5000'

# ============================================
# НАСТРОЙКИ СЕРВЕРА А (Абонент А)
# ============================================
SERVER_A_HOST = '0.0.0.0'  # '0.0.0.0' для прослушивания всех интерфейсов
SERVER_A_PORT = 5000

# ============================================
# НАСТРОЙКИ СЕРВЕРА Б (Абонент Б)
# ============================================
SERVER_B_HOST = '0.0.0.0'  # '0.0.0.0' для прослушивания всех интерфейсов
SERVER_B_PORT = 5001

# ============================================
# АДРЕСА УДАЛЁННЫХ СЕРВЕРОВ (REST API)
# ============================================
# ⚠️ ВАЖНО ДЛЯ РАБОТЫ НА ДВУХ РАЗНЫХ ПК:
# 1. Узнайте IP-адреса обоих ПК командой: ipconfig (Windows) или ip addr (Linux)
# 2. На ПК1 (server_user_1): укажите IP ПК2 в REMOTE_SERVER_B
# 3. На ПК2 (server_user_2): укажите IP ПК1 в REMOTE_SERVER_A
# 4. НЕ используйте localhost или 127.0.0.1 для работы между разными ПК!
#
# Пример:
# ПК1: IP = 172.16.111.52, порт 5000
# ПК2: IP = 172.16.111.53, порт 5001
#
# На ПК1: REMOTE_SERVER_B = 'http://172.16.111.53:5001'
# На ПК2: REMOTE_SERVER_A = 'http://172.16.111.52:5000'

# Адрес сервера А (для обращения с сервера Б)
# Сервер А (user_1) - обычно на порту 5000
# ⚠️ НА ПК2: Замените 127.0.0.1 на реальный IP-адрес ПК1!
REMOTE_SERVER_A = 'http://127.0.0.1:5000'  # ⚠️ ЗАМЕНИТЕ на IP ПК1 для работы между разными ПК!

# Адрес сервера Б (для обращения с сервера А)
# Сервер Б (user_2) - обычно на порту 5001
# ✅ НА ПК1: Уже настроено на IP ПК2
REMOTE_SERVER_B = 'http://172.16.111.53:5001'  # ✅ IP ПК2 (server_user_2)

