# Конфигурация сетевых адресов для QKD системы
# 
# Для работы на двух разных ПК:
# 1. На ПК с сервером А установите SERVER_A_HOST = '0.0.0.0' (слушать все интерфейсы)
# 2. На ПК с сервером Б установите SERVER_B_HOST = '0.0.0.0'
# 3. Укажите реальные IP-адреса в REMOTE_SERVER_A и REMOTE_SERVER_B
#
# Пример:
# ПК 1 (Абонент А): IP = 192.168.1.100
# ПК 2 (Абонент Б): IP = 192.168.1.101
#
# На ПК 1 (server_user_1):
#   SERVER_A_HOST = '0.0.0.0'
#   REMOTE_SERVER_B = 'https://192.168.1.101:5001'
#
# На ПК 2 (server_user_2):
#   SERVER_B_HOST = '0.0.0.0'
#   REMOTE_SERVER_A = 'https://192.168.1.100:5000'

import os

# Путь к директории с SSL-сертификатами
SSL_DIR = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'ssl')

# ============================================
# НАСТРОЙКИ СЕРВЕРА А (Абонент А)
# ============================================
SERVER_A_HOST = '0.0.0.0'  # '0.0.0.0' для прослушивания всех интерфейсов
SERVER_A_PORT = 5000
SERVER_A_SSL_CERT = os.path.join(SSL_DIR, 'server_a.crt')
SERVER_A_SSL_KEY = os.path.join(SSL_DIR, 'server_a.key')

# ============================================
# НАСТРОЙКИ СЕРВЕРА Б (Абонент Б)
# ============================================
SERVER_B_HOST = '0.0.0.0'  # '0.0.0.0' для прослушивания всех интерфейсов
SERVER_B_PORT = 5001
SERVER_B_SSL_CERT = os.path.join(SSL_DIR, 'server_b.crt')
SERVER_B_SSL_KEY = os.path.join(SSL_DIR, 'server_b.key')

# ============================================
# КОРНЕВОЙ CA СЕРТИФИКАТ
# ============================================
CA_CERT = os.path.join(SSL_DIR, 'ca.crt')

# ============================================
# РЕЖИМ TLS
# ============================================
# True - использовать HTTPS (TLS)
# False - использовать HTTP (без шифрования, только для разработки)
USE_TLS = False  # Установите True после генерации сертификатов

# ============================================
# АДРЕСА УДАЛЁННЫХ СЕРВЕРОВ
# ============================================
# Замените на реальные IP-адреса ваших ПК!

# Протокол зависит от USE_TLS
_PROTOCOL = 'https' if USE_TLS else 'http'

# Адрес сервера А (для обращения с сервера Б)
# Если работаете на одном ПК - используйте localhost
# Если на разных ПК - укажите IP-адрес ПК с сервером А
REMOTE_SERVER_A = f'{_PROTOCOL}://localhost:5000'
# REMOTE_SERVER_A = f'{_PROTOCOL}://192.168.1.100:5000'  # Пример для реальной сети

# Адрес сервера Б (для обращения с сервера А)
# Если работаете на одном ПК - используйте localhost
# Если на разных ПК - укажите IP-адрес ПК с сервером Б
REMOTE_SERVER_B = f'{_PROTOCOL}://localhost:5001'
# REMOTE_SERVER_B = f'{_PROTOCOL}://192.168.1.101:5001'  # Пример для реальной сети

# ============================================
# НАСТРОЙКИ БЕЗОПАСНОСТИ
# ============================================
# Проверять SSL-сертификаты при запросах (для self-signed установите False)
VERIFY_SSL = False  # Для самоподписанных сертификатов

